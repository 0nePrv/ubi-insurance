/**
 * Transactional outbox и inbox.
 *
 * <p>Что здесь будет:
 * <ul>
 *   <li>{@code OutboxWriter} — пишет запись в таблицу {@code outbox} в той же транзакции, что и бизнес-изменение;</li>
 *   <li>{@code OutboxRelay} — вычитывает неопубликованные записи ({@code FOR UPDATE SKIP LOCKED}) и отправляет в Kafka;</li>
 *   <li>{@code InboxGuard} — вставляет {@code (consumer, message_id)} в таблицу {@code inbox} в транзакции обработчика
 *       и тем самым отбрасывает повторную доставку.</li>
 * </ul>
 *
 * <p>Правило модуля: никакого доменного кода. Библиотека знает про байты, ключи партиций и заголовки,
 * но не знает, что такое полис. Схему таблиц владелец-сервис создаёт сам в своих миграциях.
 */
